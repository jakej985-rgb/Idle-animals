import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:extinction_sanctuary/core/simulation/simulation_engine.dart';
import 'package:extinction_sanctuary/models/game_state.dart';
import 'package:extinction_sanctuary/models/habitat.dart';
import 'package:extinction_sanctuary/models/species.dart';
import 'package:extinction_sanctuary/providers/game_notifier.dart';
import 'package:shared_preferences/shared_preferences.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  setUp(() {
    SharedPreferences.setMockInitialValues({});
  });

  group('Generalized Engine & Multi-Species Simulation Tests', () {
    const engine = SimulationEngine();

    test('Species registry validates all 6 species have non-zero production and capacities', () {
      expect(Species.registry.length, greaterThanOrEqualTo(6));
      for (final species in Species.registry.values) {
        expect(species.basePopulationCapacity, greaterThan(0));
        expect(species.baseBreedingSeconds, greaterThan(0));
        expect(species.baseCreditsRatePerSec, greaterThan(0));
        expect(species.baseDnaRatePerSec, greaterThan(0));
        expect(species.iconEmoji.isNotEmpty, isTrue);
      }
    });

    test('Simulation Engine ticks arbitrary species without hardcoded rules', () {
      const mammothHabitat = Habitat(
        id: 'siberian_steppe',
        name: 'Siberian Permafrost',
        biomeType: 'ice_age_tundra',
        speciesId: 'mammoth',
        population: 5,
        food: 100.0,
        maxFood: 200.0,
        water: 100.0,
        maxWater: 200.0,
      );

      final state = GameState.initial().copyWith(
        habitats: {'siberian_steppe': mammothHabitat},
        activeHabitatId: 'siberian_steppe',
        credits: 100.0,
        dna: 50.0,
      );

      final res = engine.tick(state: state, dt: 1.0);

      // Verify resources generated by mammoth
      expect(res.nextState.credits, greaterThan(state.credits));
      expect(res.nextState.dna, greaterThan(state.dna));

      // Verify food and water consumed based on mammoth species profile
      final updatedHab = res.nextState.habitats['siberian_steppe']!;
      expect(updatedHab.food, lessThan(100.0));
      expect(updatedHab.water, lessThan(100.0));
    });

    test('Breeding arbitrary species increments totalAnimalsBred counter', () {
      const aukHabitat = Habitat(
        id: 'st_kilda_isles',
        name: 'North Atlantic Crags',
        biomeType: 'northern_coast',
        speciesId: 'great_auk',
        population: 2,
        food: 100.0,
        maxFood: 100.0,
        water: 100.0,
        maxWater: 100.0,
        breedingProgress: 0.99,
      );

      final state = GameState.initial().copyWith(
        habitats: {'st_kilda_isles': aukHabitat},
        activeHabitatId: 'st_kilda_isles',
        totalAnimalsBred: 5,
      );

      // Tick 2 seconds so breeding passes 1.0
      final res = engine.tick(state: state, dt: 2.0);

      final updatedHab = res.nextState.habitats['st_kilda_isles']!;
      expect(updatedHab.population, equals(3));
      expect(res.nextState.totalAnimalsBred, equals(6));
      expect(res.nextState.totalDodosBred, equals(6)); // Backward-compatibility alias check
    });

    test('GameNotifier supports petAnimals and reviveSpecies across any habitat', () {
      final container = ProviderContainer();
      addTearDown(container.dispose);

      final notifier = container.read(gameProvider.notifier);

      // Add a custom quagga habitat
      const quaggaHab = Habitat(
        id: 'karoo_plains',
        name: 'Karoo Veld',
        biomeType: 'african_grasslands',
        speciesId: 'quagga',
        population: 0,
        food: 100.0,
        maxFood: 100.0,
        water: 100.0,
        maxWater: 100.0,
      );

      final current = container.read(gameProvider);
      final updatedHabitats = Map<String, Habitat>.from(current.habitats);
      updatedHabitats['karoo_plains'] = quaggaHab;

      // Provide ample DNA and credits to revive
      notifier.state = current.copyWith(
        habitats: updatedHabitats,
        activeHabitatId: 'karoo_plains',
        dna: 500.0,
        credits: 500.0,
      );

      // Revive species
      notifier.reviveSpecies('karoo_plains');
      expect(container.read(gameProvider).habitats['karoo_plains']!.population, equals(1));

      // Pet animals in habitat
      final creditsBefore = container.read(gameProvider).credits;
      notifier.petAnimals('karoo_plains');
      expect(container.read(gameProvider).credits, greaterThan(creditsBefore));
    });
  });
}
